-- เลิกใช้งานโหมดพิมพ์ (assignments.mode = 'print')
--
-- ครูที่ได้ไฟล์ข้อสอบไปพิมพ์ ไม่มีเหตุผลต้องกลับมาที่เว็บอีก งานทั้งหมดจึงอยู่
-- ออนไลน์อย่างเดียว — หน้า "ส่งออก & พิมพ์", ใบพิมพ์ และตัวเลือกโหมดในฟอร์ม
-- สร้างงาน ถูกถอดออกไปพร้อมกับ migration นี้
--
-- งานที่เคยตั้งเป็น 'print' ย้ายมาเป็น 'online' ทั้งหมด ไม่ได้ลบทิ้ง — โจทย์
-- คะแนน ห้องเรียน และสิ่งที่ครูตั้งไว้ยังอยู่ครบ เปลี่ยนแค่ว่านักเรียนทำบนเว็บ
-- แทนที่จะทำบนกระดาษ ถ้าไม่ย้าย งานเหล่านั้นจะค้างอยู่ในสถานะที่ไม่มีทั้งหน้า
-- พิมพ์ให้พิมพ์และไม่มีหน้าทำข้อสอบให้ทำ
UPDATE public.assignments
   SET mode = 'online'
 WHERE mode = 'print';

-- ค่า 'print' ยังคงอยู่ใน enum `assignment_mode` โดยตั้งใจ — Postgres ลบค่าใน
-- enum ไม่ได้โดยไม่สร้าง type ใหม่แล้วเขียนทุกคอลัมน์ที่อ้างถึงใหม่ ซึ่งแพงและ
-- เสี่ยงกว่าประโยชน์ที่ได้ หลังจากนี้ไม่มีโค้ดส่วนไหนเขียนค่านี้อีก และฝั่ง
-- TypeScript แคบ `AssignmentMode` เหลือ 'online' อย่างเดียวแล้ว (lib/types.ts)
-- เพื่อให้โค้ดที่เขียนรองรับใบพิมพ์ compile ไม่ผ่าน แทนที่จะค้างอยู่เงียบ ๆ
