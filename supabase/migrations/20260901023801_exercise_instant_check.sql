-- แบบฝึกหัด: กดส่งทีละข้อแล้วรู้ผลทันที
--
-- ข้อสอบกดส่งครั้งเดียวตอนจบ แบบฝึกหัดต้องบอกได้ทันทีว่าข้อนั้นถูกหรือผิด
-- แล้วให้นักเรียนแก้ตรงนั้นเลย นี่คือความต่างหลักระหว่างสองประเภท
--
-- `instant_check` เปิดปุ่ม "ตรวจคำตอบข้อนี้" ระหว่างทำ ค่าเริ่มต้นเป็น false
-- เพราะทุกงานที่แจกไปแล้วยังไม่มีปุ่มนี้ การเพิ่มคอลัมน์จึงต้องไม่เปลี่ยน
-- พฤติกรรมของ attempt ที่กำลังทำอยู่ — งานใหม่ได้ค่าเริ่มต้นเป็นเปิดจากฟอร์ม
-- สร้างแบบฝึกหัดแทน
--
-- `instant_check_answer_key` ตัดสินว่าการตรวจนั้นเปิดเฉลยด้วยหรือบอกแค่
-- ถูก/ผิด ครูที่อยากให้นักเรียนลองคิดใหม่เองปิดเฉพาะตัวนี้ได้โดยยังกดตรวจได้
ALTER TABLE public.assignments
  ADD COLUMN instant_check boolean NOT NULL DEFAULT false,
  ADD COLUMN instant_check_answer_key boolean NOT NULL DEFAULT true;

-- Backfill เฉพาะแบบฝึกหัดออนไลน์ที่ตั้ง show_results = 'immediate' อยู่แล้ว
-- นักเรียนกลุ่มนี้เห็นเฉลยทันทีที่ส่งอยู่แล้ว การกดตรวจทีละข้อจึงเปลี่ยนแค่
-- "เห็นตอนไหนภายใน attempt" ไม่ได้เปลี่ยนว่าเห็นหรือไม่เห็น ส่วนแบบฝึกหัดที่
-- ครูตั้ง score_only / after_due / never ไว้ ปล่อยปิดไว้ตามเดิม เพราะการเปิด
-- จะขัดกับสิ่งที่ครูเลือกไว้
UPDATE public.assignments
   SET instant_check = true
 WHERE type = 'exercise'
   AND mode = 'online'
   AND show_results = 'immediate';

-- นับจำนวนครั้งที่นักเรียนกดตรวจข้อนี้ระหว่างทำ
--
-- คะแนนของแบบฝึกหัดคิดจากคำตอบสุดท้ายเสมอ (submit ตอนจบตรวจใหม่ทั้งชุด) ตัวนับ
-- นี้จึงเป็นสิ่งเดียวที่บอกครูได้ว่า "ถูกตั้งแต่ครั้งแรก" ต่างจาก "ตรวจแล้วแก้
-- อีกสามรอบ" ไม่ได้ใช้คิดคะแนนและไม่ได้ใช้กั้นการกดตรวจ
ALTER TABLE public.submission_answers
  ADD COLUMN check_count integer NOT NULL DEFAULT 0
    CHECK (check_count >= 0);
