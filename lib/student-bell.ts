export type DeadlineNoticeKind = 'due-soon' | 'overdue'
export interface BellDeadline {
  due_at: string | null
  end_at: string | null
  status: string
  start_at?: string | null
}
export interface BellExtension { extended_due_at: string | null; extended_end_at: string }

/** One on-time boundary, including legacy personal extensions. */
export function studentDeadlineNotice(assignment: BellDeadline, extension: BellExtension | undefined, now: number): { kind: DeadlineNoticeKind; deadline: string; occurredAt: string } | null {
  if (!['published', 'closed'].includes(assignment.status) || !Number.isFinite(now)) return null
  const raw = extension ? extension.extended_due_at ?? extension.extended_end_at : assignment.due_at ?? assignment.end_at
  if (!raw) return null
  const due = Date.parse(raw)
  if (!Number.isFinite(due)) return null
  if (extension && (!Number.isFinite(Date.parse(extension.extended_end_at)) || due > Date.parse(extension.extended_end_at))) return null
  const remaining = due - now
  if (remaining > 86_400_000 || (assignment.status === 'closed' && remaining >= 0)) return null
  const overdue = remaining < 0
  return { kind: overdue ? 'overdue' : 'due-soon', deadline: new Date(due).toISOString(), occurredAt: new Date(overdue ? due + 1 : due - 86_400_000).toISOString() }
}

/** System reminders are generated by the bell, independent of teacher popups. */
export function isSystemDeadlineNotice(row: { type: string; actor_id?: string | null }): boolean {
  return row.type === 'assignment_reminder' && row.actor_id === null
}
